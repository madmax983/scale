#![allow(clippy::type_complexity)]
//! Spec 407: Planetary Rings.
//!
//! Planets can spawn with dense rings of high-velocity micro-debris in
//! Layer 2. The ring annulus (`radius_min..=radius_max` around the
//! planet) is a high-yield mining zone and a hazard: fleets inside it
//! take continuous density-based [`FleetHealth`] attrition. The colony
//! planet's ring also projects a Layer 1 shadow band — a band of tiles
//! across the colony map loses insolation and runs colder (the spec
//! 335 orbital-shadow / spec 403 dysonian-shadow precedent, applied to
//! the real [`TemperatureGrid`][crate::layer1::nature::temperature::
//! TemperatureGrid] inside `update_temperature_system`).
//!
//! ## Grounding audit (spec §8 pattern: adapt to the real codebase)
//!
//! * **Pre-existing stub.** Trunk already carried a `PlanetaryRing
//!   { density }` with an `InOrbit`-keyed stealth/speed/random-collision
//!   system (no annulus, no mining, no shadow). This spec extends that
//!   component in place with the spec's `radius_min` / `radius_max`
//!   annulus and replaces the random collision roll with the spec's
//!   deterministic continuous attrition (`density * 2.0` per tick,
//!   spec §4 verbatim). The stealth/speed legs are kept.
//! * **The spec sketch's `layer2::movement::Position` does not exist.**
//!   The real Layer 2 system-map position is
//!   [`Position`][crate::layer2::asteroid_redirect::Position] (built by
//!   spec 401 for exactly this map: `x` / `y` in system-map units with
//!   a `distance_to` helper). The spec's RED tests are adapted to it.
//! * **Two fleet-position legs.** Fleets with a system-map
//!   [`Position`] get the spec's annulus check verbatim
//!   ([`ring_attrition_system`]). Fleets stationed at a ringed planet
//!   via the real [`InOrbit`] leg are station-keeping inside the
//!   debris annulus by definition, so
//!   [`apply_planetary_ring_effects_system`] applies the same
//!   per-tick attrition to them (plus the legacy stealth/speed legs).
//!   Fleets outside the annulus and fleets orbiting unringed planets
//!   take no ring damage.
//! * **Mining (spec §5 REFACTOR).** The sketch's rare ring dust is
//!   mapped to the existing rare ledger resource
//!   [`ResourceType::HyperValuable`] ("Hyper-valuable resource") — no
//!   disconnected ledger is invented. Ringed planets generated by
//!   [`generate_system`][crate::layer2::generation::generate_system]
//!   carry a real [`MiningTarget`] of it, and
//!   [`ring_mining_system`] pays a density-scaled bonus of it into the
//!   real [`FleetCargo`] of any fleet already mining a ringed target
//!   through the real [`FleetMining`] seam — the trade is explicit:
//!   the same fleet is simultaneously taking annulus attrition.
//! * **Shadow projection (spec §5 REFACTOR).** The sketch's mock
//!   `Climate` does not exist. Following spec 403's dysonian pattern,
//!   [`update_ring_shadow_state_system`] mirrors the colony planet's
//!   ring into the [`PlanetaryRingState`] ledger (shadow factor +
//!   band temperature drop), and the real `update_temperature_system`
//!   applies it: tiles in the shadow band receive solar heat scaled by
//!   `1 - shadow_factor` and relax toward `ambient - band_temp_drop`
//!   after diffusion. With no ring on the colony planet the state is
//!   all-zero and both terms are exact no-ops. Only the colony
//!   planet's ring shadows the colony (other planets' rings are too
//!   far away to shade this surface) — generation rings are still
//!   mining / hazard zones.
//! * **Visuals (spec §5 REFACTOR).** The Layer 2 renderer
//!   (`layer2::render::render_system_view`) already walks
//!   `OrbitalBody` entities; ringed bodies additionally draw a faint
//!   dotted annulus at `radius_max` — the cheap seam that existed.
//! * All names are original and generic ("planetary ring", "annulus",
//!   "micro-debris" are ordinary terms). See the IP-guard test.

