    #[test]
    fn test_ring_shadow_cools_the_real_temperature_band() {
        // Integration with the REAL Layer 1 seam (the dysonian test
        // pattern): run update_temperature_system with and without a
        // ring shadow in PlanetaryRingState. Band tiles (rows 4..6 of
        // a 10-row map) must end colder; tiles outside must match.
        use crate::layer1::nature::temperature::{update_temperature_system, TemperatureGrid};
        use crate::layer1::seasons::SeasonState;
        use crate::layer1::terrain::{TerrainGrid, TerrainType};
        use bevy_ecs::system::RunSystemOnce;

        fn run(shadow: f32) -> (f32, f32) {
            let mut world = World::new();
            world.insert_resource(TemperatureGrid::new(10, 10, 15.0));
            world.insert_resource(SeasonState::default());
            world.insert_resource(crate::layer1::day_night::DayNightCycle::default());
            world.insert_resource(TerrainGrid {
                width: 10,
                height: 10,
                tiles: vec![TerrainType::Grass; 100],
            });
            if shadow > 0.0 {
                world.insert_resource(PlanetaryRingState {
                    shadow_factor: shadow,
                    band_temp_drop: ring_band_temp_drop(shadow),
                    ..Default::default()
                });
            }
            world.run_system_once(update_temperature_system).unwrap();
            let grid = world.resource::<TemperatureGrid>();
            // (x=5, y=5) is in the band; (x=5, y=0) is not.
            (grid.get(5, 5), grid.get(5, 0))
        }

        let (band_clear, out_clear) = run(0.0);
        let (band_shaded, out_shaded) = run(0.48);
        assert!(
            band_shaded < band_clear - 0.3,
            "band tile should cool under the ring shadow: {band_shaded} vs {band_clear}"
        );
        assert!(
            (out_shaded - out_clear).abs() < 1e-4,
            "tiles outside the band must be untouched: {out_shaded} vs {out_clear}"
        );
    }

