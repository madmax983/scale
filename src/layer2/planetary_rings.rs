/// FleetHealth attrition per tick per unit of ring density for a fleet
/// inside the annulus (spec §4: `density * 2.0`).
pub const RING_ATTRITION_PER_DENSITY: f32 = 2.0;
/// Bonus rare-resource yield per tick per unit of density for a fleet
/// mining a ringed target, scaled by its `FleetMining::rate`.
pub const RING_MINING_YIELD_PER_DENSITY: f32 = 0.5;
/// The existing rare resource ring mining yields — the spec's
/// rare ring dust mapped onto the real ledger (see the audit).
pub const RING_RESOURCE_TYPE: ResourceType = ResourceType::HyperValuable;
/// Mineable stock a freshly generated ring carries.
pub const RING_RESOURCE_AMOUNT: f32 = 500.0;
/// Shadow factor per unit of colony-ring density.
pub const RING_SHADOW_PER_DENSITY: f32 = 0.6;
/// Maximum ring shadow factor (a ring never blacks out the sky).
pub const MAX_RING_SHADOW_FACTOR: f32 = 0.9;
/// Band temperature drop (Celsius) at shadow factor 1.0; the band
/// relaxes toward `ambient - RING_BAND_TEMP_DROP * shadow_factor`.
pub const RING_BAND_TEMP_DROP: f32 = 10.0;
/// Fraction of map height where the ring shadow band starts / ends
/// (a band across the Y axis, per spec §5).
pub const RING_BAND_START_FRACTION: f32 = 0.4;
/// See [`RING_BAND_START_FRACTION`].
pub const RING_BAND_END_FRACTION: f32 = 0.6;
/// Default annulus for a ring with no planet radius to derive from
/// (the spec §3 sketch's radii, verbatim).
pub const DEFAULT_RADIUS_MIN: f32 = 5.0;
/// See [`DEFAULT_RADIUS_MIN`].
pub const DEFAULT_RADIUS_MAX: f32 = 10.0;

/// A planetary ring around an orbital body: a dense annulus of
/// high-velocity micro-debris (spec §4 component, extended in place
/// from the trunk stub — see the audit).
#[derive(Component, Debug, Clone, Copy, PartialEq)]
pub struct PlanetaryRing {
    /// Inner edge of the debris annulus (system-map units from the
    /// planet's center). Fleets closer than this are inside the
    /// planet's own clearance and take no attrition.
    pub radius_min: f32,
    /// Outer edge of the debris annulus.
    pub radius_max: f32,
    /// Density of the ring, affecting attrition, mining yield,
    /// stealth, and (on the colony planet) the shadow. 0.8 is the
    /// spec sketch's example density.
    pub density: f32,
}

impl Default for PlanetaryRing {
    fn default() -> Self {
        Self {
            radius_min: DEFAULT_RADIUS_MIN,
            radius_max: DEFAULT_RADIUS_MAX,
            density: 0.5,
        }
    }
}

impl PlanetaryRing {
    /// A ring with the given annulus and density.
    #[must_use]
    pub fn new(radius_min: f32, radius_max: f32, density: f32) -> Self {
        Self {
            radius_min,
            radius_max,
            density,
        }
    }

    /// A ring hugging a body of the given rendered radius: the
    /// annulus starts just clear of the surface and extends
    /// `width` units out.
    #[must_use]
    pub fn for_body_radius(body_radius: f32, width: f32, density: f32) -> Self {
        let radius_min = body_radius + 0.5;
        Self {
            radius_min,
            radius_max: radius_min + width.max(0.5),
            density,
        }
    }

    /// Whether a fleet at `distance` from the planet's center is
    /// inside the debris annulus (both edges inclusive, spec §3).
    #[must_use]
    pub fn contains_distance(&self, distance: f32) -> bool {
        distance >= self.radius_min && distance <= self.radius_max
    }

    /// Continuous FleetHealth attrition per tick inside the annulus
    /// (spec §4 formula, verbatim).
    #[must_use]
    pub fn attrition_per_tick(&self) -> f32 {
        self.density * RING_ATTRITION_PER_DENSITY
    }

    /// Bonus rare-resource yield per tick for a mining fleet with
    /// the given base mining rate stationed at this ring.
    #[must_use]
    pub fn mining_yield_per_tick(&self, mining_rate: f32) -> f32 {
        self.density * RING_MINING_YIELD_PER_DENSITY * mining_rate
    }
}

/// Shadow factor for a colony-ring density (0.0 with no ring).
#[must_use]
pub fn ring_shadow_factor(density: f32) -> f32 {
    (density.max(0.0) * RING_SHADOW_PER_DENSITY).clamp(0.0, MAX_RING_SHADOW_FACTOR)
}

/// Band temperature drop (Celsius) for a shadow factor.
#[must_use]
pub fn ring_band_temp_drop(shadow_factor: f32) -> f32 {
    RING_BAND_TEMP_DROP * shadow_factor.clamp(0.0, MAX_RING_SHADOW_FACTOR)
}

/// Rows of a map of the given height that fall inside the ring
/// shadow band (spec §5: a band of tiles on the Y axis).
#[must_use]
#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
pub fn ring_shadow_band(height: usize) -> std::ops::Range<usize> {
    let start = (height as f32 * RING_BAND_START_FRACTION) as usize;
    let end = ((height as f32 * RING_BAND_END_FRACTION) as usize).max(start + 1);
    start..end.min(height.max(1))
}

/// Whether map row `y` of a map with the given height is shadowed.
#[must_use]
pub fn in_ring_shadow_band(y: usize, height: usize) -> bool {
    ring_shadow_band(height).contains(&y)
}

/// Layer 1 shadow ledger for the colony planet's ring: the mirror
/// the real temperature system reads (the spec-403 `DysonianState`
/// pattern). All-zero when the colony planet has no ring.
#[derive(Resource, Debug, Clone)]
pub struct PlanetaryRingState {
    /// Total ringed planets in the system.
    pub ring_count: usize,
    /// Density of the colony planet's ring (0.0 when it has none).
    pub colony_density: f32,
    /// Fraction of sunlight the colony ring blocks in its band.
    pub shadow_factor: f32,
    /// Celsius the shadow band relaxes below ambient.
    pub band_temp_drop: f32,
    /// One-shot: the first-shadow chronicle was written.
    pub shadow_chronicled: bool,
}

impl Default for PlanetaryRingState {
    fn default() -> Self {
        Self {
            ring_count: 0,
            colony_density: 0.0,
            shadow_factor: 0.0,
            band_temp_drop: 0.0,
            shadow_chronicled: false,
        }
    }
}

/// Spec system (verbatim shape): fleets positioned inside a ring's
/// annulus on the system map take continuous density-based attrition;
/// fleets outside it (or inside the inner clearance) take none.
pub fn ring_attrition_system(
    ring_query: Query<(&PlanetaryRing, &Position)>,
    mut fleet_query: Query<(&mut FleetHealth, &Position), With<Fleet>>,
) {
    for (ring, r_pos) in ring_query.iter() {
        for (mut health, f_pos) in fleet_query.iter_mut() {
            let dist = r_pos.distance_to(*f_pos);
            if ring.contains_distance(dist) {
                health.current = (health.current - ring.attrition_per_tick()).max(0.0);
            }
        }
    }
}

/// Legacy `InOrbit` leg (extended): fleets stationed at a ringed
/// planet are station-keeping inside its debris annulus. Applies the
/// legacy stealth/speed effects plus the spec's deterministic
/// attrition (replacing the stub's random collision roll).
pub fn apply_planetary_ring_effects_system(
    ring_query: Query<&PlanetaryRing>,
    mut fleet_query: Query<
        (
            &InOrbit,
            Option<&mut VisibilityStatus>,
            Option<&mut MovementSpeed>,
            Option<&mut FleetHealth>,
        ),
        With<Fleet>,
    >,
) {
    for (in_orbit, mut maybe_visibility, mut maybe_speed, mut maybe_health) in &mut fleet_query {
        if let Ok(ring) = ring_query.get(in_orbit.parent) {
            // Stealth bonus: a dense enough ring hides the fleet.
            if let Some(visibility) = maybe_visibility.as_mut() {
                if ring.density > 0.5 {
                    visibility.is_visible = false;
                }
            }

            // Speed bonus: the debris stream carries the fleet.
            if let Some(speed) = maybe_speed.as_mut() {
                let speed_boost = 1.0 + (0.2 * ring.density);
                speed.current = speed.base * speed_boost;
            }

            // Continuous micro-debris attrition (spec §4 rate).
            if let Some(health) = maybe_health.as_mut() {
                health.current = (health.current - ring.attrition_per_tick()).max(0.0);
            }
        } else {
            // Reset speed if not in a ring.
            if let Some(speed) = maybe_speed.as_mut() {
                speed.current = speed.base;
            }
            // Visibility is not reset here unconditionally, as it may
            // be affected by other systems (e.g. sensor occlusion).
        }
    }
}

/// Mining integration (spec §5 REFACTOR): a fleet already mining a
/// ringed target through the real [`FleetMining`] seam earns a
/// density-scaled bonus of the ring's rare resource into its real
/// [`FleetCargo`], on top of the target's normal yield. The fleet is
/// simultaneously paying the annulus attrition — that is the trade.
pub fn ring_mining_system(
    mut fleets: Query<(&FleetMining, &mut FleetCargo)>,
    rings: Query<&PlanetaryRing>,
) {
    for (mining, mut cargo) in &mut fleets {
        if let Ok(ring) = rings.get(mining.target) {
            let bonus = ring.mining_yield_per_tick(mining.rate);
            if bonus > 0.0 {
                cargo.add(RING_RESOURCE_TYPE, bonus);
            }
        }
    }
}

/// Recompute the Layer 1 shadow ledger from the colony planet's
/// ring and write the one-shot first-shadow chronicle. Other
/// planets' rings count toward the census but cast no shadow here.
pub fn update_ring_shadow_state_system(
    rings: Query<&PlanetaryRing>,
    colony_rings: Query<&PlanetaryRing, With<ColonyLocation>>,
    state: Option<ResMut<PlanetaryRingState>>,
    mut chronicle: EventWriter<AddChronicleEvent>,
) {
    let ring_count = rings.iter().count();
    let colony_density = colony_rings.iter().next().map_or(0.0, |r| r.density);
    let shadow = ring_shadow_factor(colony_density);
    let Some(mut state) = state else { return };
    state.ring_count = ring_count;
    state.colony_density = colony_density;
    state.shadow_factor = shadow;
    state.band_temp_drop = ring_band_temp_drop(shadow);
    if shadow > 0.0 && !state.shadow_chronicled {
        state.shadow_chronicled = true;
        chronicle.send(AddChronicleEvent {
            text: "A RING SHADOW: the colony planet's ring has swung across the sun — a cold band of shade now crosses the colony map, dimming the tiles beneath it while the debris overhead glitters with mineable wealth.".to_string(),
            importance: EventImportance::Major,
        });
    }
}

