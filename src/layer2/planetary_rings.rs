/// Census of the ring layer for STATS / panels.
#[derive(Debug, Clone, Copy, Default)]
pub struct PlanetaryRingCensus {
    /// Ringed planets in the system.
    pub rings: usize,
    /// Whether the colony planet itself is ringed.
    pub colony_ring: bool,
    /// Densest ring in the system.
    pub max_density: f32,
    /// Current Layer 1 shadow factor from the colony ring.
    pub shadow: f32,
    /// Current band temperature drop (Celsius).
    pub band_drop: f32,
}

/// Census of rings, colony-ring presence, and shadow.
#[must_use]
pub fn planetary_ring_census(world: &mut World) -> PlanetaryRingCensus {
    let mut rings = 0usize;
    let mut max_density = 0.0f32;
    {
        let mut q = world.query::<&PlanetaryRing>();
        for ring in q.iter(world) {
            rings += 1;
            max_density = max_density.max(ring.density);
        }
    }
    let colony_density = {
        let mut q = world.query_filtered::<&PlanetaryRing, With<ColonyLocation>>();
        q.iter(world).next().map_or(0.0, |r| r.density)
    };
    // Prefer the live ledger when present (it is what temperature
    // actually applies); fall back to the derived colony shadow.
    let (shadow, band_drop) = world.get_resource::<PlanetaryRingState>().map_or_else(
        || {
            let shadow = ring_shadow_factor(colony_density);
            (shadow, ring_band_temp_drop(shadow))
        },
        |s| (s.shadow_factor, s.band_temp_drop),
    );
    PlanetaryRingCensus {
        rings,
        colony_ring: colony_density > 0.0,
        max_density,
        shadow,
        band_drop,
    }
}

/// Compact STATS label, e.g. `2rings/0.80max/0.48shadow`. No spaces.
#[must_use]
pub fn rings_stats_label(world: &mut World) -> String {
    let census = planetary_ring_census(world);
    format!(
        "{}rings/{:.2}max/{:.2}shadow",
        census.rings, census.max_density, census.shadow
    )
}

/// Spawn a standalone ringed planet (headless / test helper): a real
/// [`SystemBody`] + [`OrbitalBody`] carrying the ring, its system-map
/// [`Position`], and a real [`MiningTarget`] of the ring resource.
pub fn spawn_ringed_planet(world: &mut World, density: f32) -> Entity {
    world
        .spawn((
            SystemBody,
            OrbitalBody {
                name: "Ringed Planet".to_string(),
                radius: 2.0,
                color: ratatui::style::Color::Cyan,
                char: 'O',
            },
            PlanetaryRing::for_body_radius(2.0, 5.0, density),
            Position { x: 0.0, y: 0.0 },
            MiningTarget {
                resource_type: RING_RESOURCE_TYPE,
                amount: RING_RESOURCE_AMOUNT,
                mining_difficulty: 1.5,
            },
        ))
        .id()
}

/// Attach a ring to the colony planet (the headless `ring` leg):
/// finds the [`ColonyLocation`] planet (falling back to any
/// `SystemBody`, then to a freshly spawned ringed planet), sizes the
/// annulus from its body radius, and ensures it carries the ring
/// [`MiningTarget`] and a system-map [`Position`]. Returns the
/// planet entity.
pub fn ensure_colony_ring(world: &mut World, density: f32) -> Entity {
    let existing = {
        let mut q = world.query_filtered::<Entity, With<ColonyLocation>>();
        q.iter(world).next()
    }
    .or_else(|| {
        let mut q = world.query_filtered::<Entity, With<SystemBody>>();
        q.iter(world).next()
    });
    let Some(planet) = existing else {
        let planet = spawn_ringed_planet(world, density);
        world.entity_mut(planet).insert(ColonyLocation);
        return planet;
    };
    let body_radius = world.get::<OrbitalBody>(planet).map_or(2.0, |b| b.radius);
    let mut entity = world.entity_mut(planet);
    entity.insert(PlanetaryRing::for_body_radius(body_radius, 5.0, density));
    if entity.get::<MiningTarget>().is_none() {
        entity.insert(MiningTarget {
            resource_type: RING_RESOURCE_TYPE,
            amount: RING_RESOURCE_AMOUNT,
            mining_difficulty: 1.5,
        });
    }
    if entity.get::<Position>().is_none() {
        entity.insert(Position { x: 0.0, y: 0.0 });
    }
    planet
}

