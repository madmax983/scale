/// Types of memories a pop can acquire.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MemoryType {
    /// Witnessed a pop die.
    WitnessedDeath,
    /// Suffered from starvation (hunger = 0).
    StarvationTrauma,
    /// Ate a high quality meal.
    AteFineMeal,
    /// Won a combat encounter.
    WonFight,
    /// Saw a dead body (corpse).
    SawCorpse,
    /// Attended a funeral (closure).
    AttendedFuneral,
    FleshTaxTrauma,
    /// Slept in an awful room.
    SleptInAwfulRoom,
    /// Slept in a dull room.
    SleptInDullRoom,
    /// Slept in a decent room.
    SleptInDecentRoom,
    /// Slept in a great room.
    SleptInGreatRoom,
    /// Slept in a legendary room.
    SleptInLegendaryRoom,
    /// Ate in an awful room.
    AteInAwfulRoom,
    /// Ate in a dull room.
    AteInDullRoom,
    /// Ate in a decent room.
    AteInDecentRoom,
    /// Ate in a great room.
    AteInGreatRoom,
    /// Ate in a legendary room.
    AteInLegendaryRoom,
    /// Admired a piece of art.
    AdmiredArt,
    /// Disgusted by vermin infestation.
    DisgustedByVermin,
    /// Inspector gave a glowing report.
    InspectorImpressed,
    /// Inspector gave a terrible report.
    InspectorDisappointed,
    /// Fake positive memory generated by a Simulacrum.
    FakePositive,
    /// The colony mascot died.
    MascotDeath,
    /// Lost a limb in an accident.
    LostLimb,
    /// Ate the flesh of another pop (Spec 276: taboo violation).
    CannibalismTaboo,
    /// Psychological trauma from consuming sapient flesh (Spec 276).
    CannibalismTrauma,
    /// Learned a craft by working alongside a master (Spec 339).
    LearnedFromMentor,
    /// Passed hard-won craft on to a novice (Spec 339).
    TaughtNovice,
    /// Lived through a colony-wide famine (Spec 341).
    SurvivedFamine,
    /// Was there at the founding of the colony (Spec 341).
    ColonyFounder,
    /// Ground down by structural conditions (Spec 1387) — a summary of
    /// the dissatisfaction ledger at a Bitter crossing; deliberately
    /// small next to the bridge modifier, which does the heavy lifting.
    GroundDown,
}

impl MemoryType {
    /// Returns the mood impact (0.0 to 1.0 or negative).
    #[must_use]
    pub const fn base_mood_impact(&self) -> f32 {
        match self {
            Self::WitnessedDeath => -0.2,
            Self::MascotDeath | Self::LostLimb | Self::FleshTaxTrauma => -0.3, // High impact grief/trauma
            Self::CannibalismTaboo => -0.25,
            Self::CannibalismTrauma => -0.35, // Eating the dead scars deeply
            Self::StarvationTrauma => -0.15,
            Self::DisgustedByVermin | Self::InspectorDisappointed => -0.1,
            Self::InspectorImpressed => 0.15,
            Self::FakePositive => 0.5,
            Self::AteFineMeal | Self::AttendedFuneral => 0.1,
            Self::WonFight | Self::AdmiredArt => 0.05,
            Self::LearnedFromMentor | Self::TaughtNovice => 0.05, // Spec 339: the warmth of craft passed on
            Self::SurvivedFamine => -0.10, // Spec 341: the hunger years leave a mark
            Self::ColonyFounder => 0.05, // Spec 341: quiet pride of the first landing
            Self::GroundDown => -0.1, // Spec 1387: summary of the ledger; the bridge does the heavy lifting
            Self::SawCorpse => -0.05,
            Self::SleptInAwfulRoom => -0.1,
            Self::SleptInDullRoom => -0.05,
            Self::SleptInGreatRoom => 0.05,
            Self::SleptInLegendaryRoom => 0.1,
            Self::AteInAwfulRoom => -0.05,
            Self::AteInDullRoom => -0.02,
            Self::SleptInDecentRoom | Self::AteInDecentRoom => 0.0,
            Self::AteInGreatRoom => 0.02,
            Self::AteInLegendaryRoom => 0.05,
        }
    }

    /// Returns the decay rate per tick.
    #[must_use]
    pub const fn decay_rate(&self) -> f32 {
        // Ticks to fade completely
        match self {
            Self::WitnessedDeath | Self::LostLimb | Self::MascotDeath => 0.0005, // Slow fade (2000 ticks)
            Self::CannibalismTaboo | Self::CannibalismTrauma => 0.0005, // Slow fade (2000 ticks): the colony does not forget
            Self::StarvationTrauma | Self::AttendedFuneral | Self::FleshTaxTrauma => 0.001, // Medium
            Self::AteFineMeal | Self::WonFight => 0.002, // Fast (500 ticks)
            Self::LearnedFromMentor | Self::TaughtNovice => 0.002, // Spec 339: Fast (500 ticks), like other craft joys
            Self::SurvivedFamine => 0.0005, // Spec 341: slow fade, like WitnessedDeath
            Self::ColonyFounder => 0.0002, // Spec 341: founding is identity — fades slowest of all
            Self::GroundDown => 0.0005, // Spec 1387: slow fade — outlives the ledger's decay tail
            Self::SawCorpse | Self::AdmiredArt | Self::DisgustedByVermin => 0.01, // Very fast fade (100 ticks)
            Self::InspectorImpressed | Self::InspectorDisappointed | Self::FakePositive => 0.005, // Medium-long duration (~200 ticks)
            // Room thoughts last 1 day (100 ticks)
            Self::SleptInAwfulRoom
            | Self::SleptInDullRoom
            | Self::SleptInDecentRoom
            | Self::SleptInGreatRoom
            | Self::SleptInLegendaryRoom
            | Self::AteInAwfulRoom
            | Self::AteInDullRoom
            | Self::AteInDecentRoom
            | Self::AteInGreatRoom
            | Self::AteInLegendaryRoom => 0.01,
        }
    }
}

/// A specific instance of a memory on a pop.
#[derive(Debug, Clone)]
pub struct ActiveMemory {
    /// The type of memory.
    pub memory_type: MemoryType,
    /// The tick when it was added.
    pub added_at: u64,
    /// Current intensity (starts at 1.0, decays to 0.0).
    pub intensity: f32,
    /// Indicates if this memory was artificially forged.
    pub forged: bool,
}

/// Component storing all active memories for a pop.
#[derive(Component, Default, Debug, Clone)]
pub struct Memories {
    /// List of active memories.
    pub items: Vec<ActiveMemory>,
}

impl Memories {
    /// Adds a new memory with full intensity.
    pub fn add(&mut self, memory_type: MemoryType, current_tick: u64) {
        self.items.push(ActiveMemory {
            memory_type,
            added_at: current_tick,
            intensity: 1.0,
            forged: false,
        });
    }

    /// Adds a forged memory with full intensity.
    pub fn add_forged(&mut self, memory_type: MemoryType, current_tick: u64) {
        self.items.push(ActiveMemory {
            memory_type,
            added_at: current_tick,
            intensity: 1.0,
            forged: true,
        });
    }

    /// Adds a memory with a specific starting intensity (Spec 341).
    ///
    /// Intensity is clamped to `0.0..=1.0`. Enforces
    /// [`MAX_MEMORIES_PER_POP`]: when the cap is exceeded, the weakest
    /// memories are forgotten first.
    pub fn add_with_intensity(
        &mut self,
        memory_type: MemoryType,
        current_tick: u64,
        intensity: f32,
    ) {
        self.items.push(ActiveMemory {
            memory_type,
            added_at: current_tick,
            intensity: intensity.clamp(0.0, 1.0),
            forged: false,
        });
        // Spec 341 §7: a pop can only carry so much. When the cap is
        // exceeded, the weakest memories are forgotten first.
        while self.items.len() > MAX_MEMORIES_PER_POP {
            let weakest = self
                .items
                .iter()
                .enumerate()
                .min_by(|(_, a), (_, b)| a.intensity.total_cmp(&b.intensity))
                .map(|(i, _)| i);
            match weakest {
                Some(i) => {
                    self.items.remove(i);
                }
                None => break,
            }
        }
    }

    /// Returns true if the pop holds at least one memory of the given type.
    #[must_use]
    pub fn has_memory(&self, memory_type: MemoryType) -> bool {
        self.items.iter().any(|m| m.memory_type == memory_type)
    }

    /// Total weight (summed intensity) of the pop's memories of a type.
    #[must_use]
    pub fn memory_weight(&self, memory_type: MemoryType) -> f32 {
        self.items
            .iter()
            .filter(|m| m.memory_type == memory_type)
            .map(|m| m.intensity)
            .sum()
    }

    /// Decays all memories by the given number of ticks.
    /// Removes memories that have faded to 0 intensity.
    pub fn decay(&mut self, ticks_passed: u64) {
        #[allow(clippy::cast_precision_loss)]
        let ticks_f32 = ticks_passed as f32;
        for memory in &mut self.items {
            let decay = memory.memory_type.decay_rate() * ticks_f32;
            memory.intensity = (memory.intensity - decay).max(0.0);
        }
        self.items.retain(|m| m.intensity > 0.0);
    }
}

/// Calculates the raw (unclamped) morale score.
#[must_use]
pub fn calculate_raw_morale(
    needs: &Needs,
    memories: Option<&Memories>,
    social_buff: Option<&SocialBuff>,
    policies: Option<&ColonyPolicies>,
    traits: Option<&Traits>,
    time_of_day: Option<TimeOfDay>,
    morale: Option<&Morale>,
) -> f32 {
    let base = needs.morale();
    let memory_modifier: f32 = memories.map_or(0.0, |m| {
        m.items
            .iter()
            .map(|i| i.memory_type.base_mood_impact() * i.intensity)
            .sum()
    });

    let social_modifier = social_buff.map_or(0.0, |s| s.value);

    let policy_modifier = policies.map_or(0.0, get_morale_modifier);

    let trait_modifier = if let (Some(t), Some(time)) = (traits, time_of_day) {
        get_trait_mood_modifier(t, time)
    } else {
        0.0
    };

    let morale_modifier: f32 =
        morale.map_or(0.0, |m| m.modifiers.iter().map(|modi| modi.value).sum());

    base + memory_modifier + social_modifier + policy_modifier + trait_modifier + morale_modifier
}

/// Calculates the effective morale including memory and social modifiers.
#[must_use]
pub fn calculate_effective_morale(
    needs: &Needs,
    memories: Option<&Memories>,
    social_buff: Option<&SocialBuff>,
    policies: Option<&ColonyPolicies>,
    traits: Option<&Traits>,
    time_of_day: Option<TimeOfDay>,
    morale: Option<&Morale>,
) -> f32 {
    calculate_raw_morale(
        needs,
        memories,
        social_buff,
        policies,
        traits,
        time_of_day,
        morale,
    )
    .clamp(0.0, 1.0)
}

/// System to decay memories every tick.
pub fn memory_decay_system(mut query: Query<&mut Memories>) {
    // Assuming this runs every tick
    query.par_iter_mut().for_each(|mut memories| {
        memories.decay(1);
    });
}

