/// The first line of the board. It marks the file as generated.
pub const BOARD_HEADER: &str = "<!-- Generated by `mesh`. Do not edit. Run `mesh board` to refresh. -->";

/// Board groups, in display order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Group {
    /// Submitted, all dependencies completed.
    Ready,
    /// Claimed.
    Working,
    /// Waiting for an answer.
    InputRequired,
    /// Submitted, waiting for dependencies.
    Waiting,
    /// Submitted, a dependency failed or was canceled.
    Blocked,
    /// Failed.
    Failed,
    /// Completed.
    Completed,
    /// Canceled.
    Canceled,
}

impl Group {
    /// All groups, in display order.
    pub const ALL: [Self; 8] = [
        Self::Ready,
        Self::Working,
        Self::InputRequired,
        Self::Waiting,
        Self::Blocked,
        Self::Failed,
        Self::Completed,
        Self::Canceled,
    ];

    /// The display name.
    #[must_use]
    pub const fn title(self) -> &'static str {
        match self {
            Self::Ready => "ready",
            Self::Working => "working",
            Self::InputRequired => "input-required",
            Self::Waiting => "waiting",
            Self::Blocked => "blocked",
            Self::Failed => "failed",
            Self::Completed => "completed",
            Self::Canceled => "canceled",
        }
    }
}

