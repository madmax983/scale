#[cfg(test)]
mod tests {
    use super::*;
    use crate::event::TaskSpec;
    use crate::ids::{AgentId, Skill, TaskId};
    use crate::ledger::{Command, Ctx};
    use crate::registry::{Registry, DEFAULT_REGISTRY};

    fn tid(s: &str) -> TaskId {
        TaskId::new(s).unwrap_or_else(|e| panic!("{e}"))
    }

    fn sample() -> Ledger {
        let r = Registry::parse(DEFAULT_REGISTRY).unwrap_or_else(|e| panic!("{e}"));
        let skill = |s: &str| Skill::new(s).unwrap_or_else(|e| panic!("{e}"));
        let mut a = TaskSpec::new(tid("a"), "Build | the thing", skill("build"));
        a.paths = vec!["src/**".into()];
        let mut b = TaskSpec::new(tid("b"), "Review", skill("review"));
        b.deps = vec![tid("a")];
        let c = TaskSpec::new(tid("c"), "Spec", skill("spec"));
        let mut l = Ledger::new();
        let ctx = Ctx { now: 1_700_000_000, registry: &r };
        l.execute(Command::Plan(vec![a, b, c]), &ctx).unwrap_or_else(|e| panic!("{e}"));
        l.execute(
            Command::Claim { task: Some(tid("a")), agent: AgentId::new("builder").unwrap_or_else(|e| panic!("{e}")), worker: None, ttl: 60 },
            &ctx,
        )
        .unwrap_or_else(|e| panic!("{e}"));
        l
    }

    #[test]
    fn groups_and_counts() {
        let l = sample();
        let g = |id: &str| group_of(&l, l.task(&tid(id)).unwrap_or_else(|| panic!("{id}")));
        assert_eq!(g("a"), Group::Working);
        assert_eq!(g("b"), Group::Waiting);
        assert_eq!(g("c"), Group::Ready);
        let c = counts(&l);
        assert_eq!(c.len(), Group::ALL.len());
        assert_eq!(c.iter().map(|(_, n)| n).sum::<usize>(), 3);
        assert!(c.contains(&(Group::Working, 1)));
    }

    #[test]
    fn render_is_stable_and_escapes_tables() {
        let l = sample();
        let text = render(&l);
        assert_eq!(text, render(&l));
        assert!(text.starts_with(BOARD_HEADER));
        assert!(text.contains("## working (1)"));
        assert!(text.contains("Build \\| the thing"));
        assert!(text.contains("2023-11-14T22:14:20Z"));
        assert!(text.ends_with('\n'));
        let ready = text.find("## ready").unwrap_or(0);
        let working = text.find("## working").unwrap_or(0);
        assert!(ready < working);
    }

    #[test]
    fn empty_board_says_so() {
        assert!(render(&Ledger::new()).contains("No tasks."));
    }
}
